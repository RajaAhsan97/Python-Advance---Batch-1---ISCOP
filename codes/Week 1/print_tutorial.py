# Python is case sensitive language
# print() function
# 1. It is a built-in function of python, it can print any value given to it
# 2. print function can take no value
# 3. It can print any number of values comma seperated

# Value --> Data (Types)
#    a. numbers
#         i. whole numbers  for e.g. 0,1,2,3,4   ---> integer
#         ii. decimal numbers for e.g. 2.4 etc   ---> float

#    b. text
#         i. strings --> sequence of characters  'Ahsan' or "Ahsan" or '''Ahsan''' or """Ahsan"""
# 
#    c. Boolean
#            True and False

print(23)   # integer value

print(2.5)  # float value

print('Raja AHsan')

print('''Raja Ahsan - 
ISCOP institute''')

print("""Raja Ahsan - 
ISCOP institute""")

print()

print("Raja Ahsan", 5, 10)

